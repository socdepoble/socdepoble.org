export const TEXTOS = Object.freeze({
  ca: Object.freeze(CA), es: Object.freeze(ES), en: Object.freeze(EN), eu: Object.freeze(EU), gl: Object.freeze(GL)
});

const LLENGUES = Object.freeze(Object.keys(TEXTOS));

/** La llengua admesa més pròxima: una de les cinc o 'ca'. */
export const llenguaDe = (idioma) => (typeof idioma === 'string' && LLENGUES.includes(idioma) ? idioma : 'ca');

/**
 * El text de `clau` en `idioma`, amb {nom} substituït per String(valor). Cau
 * al valencià i, si tampoc hi és, torna la clau (mai un buit mut). La
 * substitució es fa amb split/join: cap expressió regular dinàmica.
 */
export function t(idioma, clau, valors = {}) {
  const taula = TEXTOS[llenguaDe(idioma)];
  const base = Object.hasOwn(taula, clau) ? taula[clau] : (Object.hasOwn(CA, clau) ? CA[clau] : String(clau));
  let text = base;
  for (const nom of Object.keys(valors || {})) text = text.split(`{${nom}}`).join(String(valors[nom]));
  return text;
}

/** Una frase per a una alerta de cronologia.js; el nom de les persones el dona `nomDe(id)`. */
export function textAlerta(alerta, idioma, nomDe) {
  const tipus = typeof alerta?.tipus === 'string' ? alerta.tipus : '';
  const clau = Object.hasOwn(CA, `alerta.${tipus}`) ? `alerta.${tipus}` : 'alerta.desconeguda';
  const nom = alerta?.personaId ? nomDe(alerta.personaId) : '';
  const altra = alerta?.altraId ? nomDe(alerta.altraId) : '';
  return t(idioma, clau, { nom, altra });
}

/** El text d'un error del magatzem (pel seu codi) o d'una dada no vàlida. */
export function textError(error, idioma) {
  if (error?.codiLectura) return textCodiLectura(error.codiLectura, idioma);
  const codi = typeof error === 'string' ? error : error?.codi ?? error?.clau;
  switch (codi) {
    case 'NOMES_LECTURA': return t(idioma, 'error.NOMES_LECTURA');
    case 'BLOQUEJAT': return t(idioma, 'error.BLOQUEJAT');
    case 'VERSIO_ANTIGA':
    case 'NO_DISPONIBLE': return t(idioma, 'error.VERSIO_ANTIGA');
    case 'desactualitzat': return t(idioma, 'error.desactualitzat');
    case 'duplicat-conflicte': return t(idioma, 'error.duplicat-conflicte');
    case 'invalid': return t(idioma, 'error.invalid');
    default: return error instanceof TypeError ? t(idioma, 'error.invalid') : t(idioma, 'error.desa');
  }
}

const XIFRES = /^\d{1,7}$/;

/**
 * El text d'un codi d'error o d'avís de llegeixGedcom o llegeixCopiaJson
 * ('capcalera', 'linia-malformada:12', 'persona-invalida:3', 'mes-avisos:9').
 * El sufix «:n» és el número de línia del GEDCOM o, en una còpia JSON
 * (`json: true`), l'índex del registre (es mostra comptant des d'1). Un codi
 * desconegut dona un text genèric traduït, mai la clau crua.
 */
export function textCodiLectura(codi, idioma, { json = false } = {}) {
  const cru = typeof codi === 'string' ? codi : '';
  const dosPunts = cru.indexOf(':');
  const base = dosPunts === -1 ? cru : cru.slice(0, dosPunts);
  const sufix = dosPunts === -1 ? '' : cru.slice(dosPunts + 1);
  const n = XIFRES.test(sufix) ? Number(sufix) : null;
  const clau = `importa.codi.${base}`;
  if (base === '' || !Object.hasOwn(CA, clau)) return t(idioma, 'importa.codi.desconegut');
  if (base === 'mes-avisos') return t(idioma, clau, { n: n ?? 0 });
  const text = t(idioma, clau);
  if (n === null) return text;
  return json ? t(idioma, 'importa.codi.registre', { text, n: n + 1 }) : t(idioma, 'importa.codi.linia', { text, n });
}

/** «Persona viva» quan filtraVius l'ha anonimitzada; si no, el nom i els cognoms. */
export function nomVisible(persona, idioma) {
  if (!persona) return '';
  if (persona.privada) return t(idioma, 'persona.viva');
  const nom = [persona.nom, persona.cognom1, persona.cognom2].filter((part) => typeof part === 'string' && part.trim()).join(' ');
  return nom || t(idioma, 'persona.senseNom');
}

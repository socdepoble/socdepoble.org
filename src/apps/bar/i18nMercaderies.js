export const CODIS_IDIOMA_MERCADERIES = Object.freeze(['ca', 'es', 'en', 'eu', 'gl']);

export function codiIdiomaMercaderies(idioma) {
  const codi = String(idioma || 'ca').toLowerCase().split('-')[0];
  return CODIS_IDIOMA_MERCADERIES.includes(codi) ? codi : 'ca';
}


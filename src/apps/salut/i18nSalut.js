export function codiIdiomaSalut(idioma) {
  const codi = String(idioma || 'ca').toLowerCase().split('-')[0];
  return Object.hasOwn(TEXTOS_SALUT, codi) ? codi : 'ca';
}

export function textosSalut(idioma) {
  return TEXTOS_SALUT[codiIdiomaSalut(idioma)];
}

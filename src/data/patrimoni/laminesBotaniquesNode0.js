const EQUIP_VISUAL = Object.freeze(['Claude', 'Codex', 'Gemini Carbon']);
const LLICENCIA_LLIURE = /^(?:CC0-1\.0|PDM-1\.0|Domini públic|CC-BY-3\.0-US|CC-BY(?:-SA)?-(?:2\.0|2\.5|3\.0|4\.0))$/u;

function rutaLlicencia(llicencia) {
  if (llicencia === 'CC-BY-3.0-US') return '/licenses/by/3.0/us/';
  if (llicencia === 'CC0-1.0') return '/publicdomain/zero/1.0/';
  if (llicencia === 'PDM-1.0' || llicencia === 'Domini públic') return '/publicdomain/mark/1.0/';
  const [, classe, versio] = /^CC-(BY(?:-SA)?)-(.+)$/u.exec(llicencia);
  return `/licenses/${classe.toLowerCase()}/${versio}/`;
}

export function potMostrarVariantBotanica(variant) {
  if (!variant || typeof variant !== 'object') return false;
  const { estatVisual, tipusImatge, autor, titolImatge, llicencia, llicenciaUrl, urlOrigen, verificadors } = variant;
  if (estatVisual !== 'verificada' || typeof autor !== 'string' || !autor.trim() ||
      typeof titolImatge !== 'string' || !titolImatge.trim() ||
      typeof llicencia !== 'string' || !LLICENCIA_LLIURE.test(llicencia) ||
      !Array.isArray(verificadors)) return false;
  const esFoto = tipusImatge === 'fotografia-real-verificada';
  if (!esFoto && tipusImatge !== 'recreacio-auditada') return false;
  const equip = esFoto ? [...EQUIP_VISUAL, 'Node 0'] : EQUIP_VISUAL;
  if (!equip.every((nom) => verificadors.includes(nom))) return false;
  try {
    const url = new URL(urlOrigen);
    const llicenciaCanonica = `https://creativecommons.org${rutaLlicencia(llicencia)}`;
    if (url.protocol !== 'https:' || url.username || url.password || url.port || llicenciaUrl !== llicenciaCanonica) return false;
    if (!esFoto) return true;
    return (url.hostname === 'commons.wikimedia.org' && /^\/wiki\/File:[^/]+$/u.test(url.pathname)) ||
      (url.hostname === 'www.gbif.org' && /^\/occurrence\/\d+$/u.test(url.pathname));
  } catch {
    return false;
  }
}


/**
 * Resol qualsevol URL de socdepoble.net (o camí relatiu antic) cap a la ruta
 * canònica interna de l'aplicació Sóc de Poble (/mur/:slug, /events/:slug,
 * /page/:slug, /pobles/:slug). Retorna null si és un enllaç extern aliè.
 */
export function resolRutaInternaSocDePobleNet(rawHref) {
  if (typeof rawHref !== 'string' || !rawHref.trim()) return null;
  const trimmed = rawHref.trim();

  // Si ja és una ruta interna canònica
  if (/^\/(?:mur|events|page|pobles|mercat|calendari|xat|wikidepoble)(?:\/|$|\?|#)/.test(trimmed)) {
    return trimmed;
  }

  let parsed;
  try {
    parsed = new URL(trimmed, 'https://socdepoble.net');
  } catch {
    return null;
  }

  const host = parsed.hostname.toLowerCase().replace(/^www\./, '');
  if (host !== 'socdepoble.net' && host !== 'socdepoble.org' && host !== 'socdepoble.cat' && !host.endsWith('.blogspot.com')) {
    return null;
  }

  // No reescriure fitxers de wp-content/uploads directament com a ruta de pàgina
  if (/^\/wp-content\//i.test(parsed.pathname)) {
    return null;
  }

  const hash = parsed.hash || '';
  const cleanPath = parsed.pathname.replace(/^\/+|\/+$/g, '');
  if (!cleanPath) return '/' + hash;

  const segments = cleanPath.split('/').filter(Boolean);
  const lastSlug = segments[segments.length - 1]?.replace(/\.html$/i, '') || '';

  // 1. Enllaç de categoria (/category/.../:slug/)
  if (segments[0] === 'category' || segments[0] === 'categoria') {
    const dest = MAPA_CATEGORIES_WP_114[lastSlug] || `/pobles/${lastSlug}`;
    return dest + hash;
  }

  // 2. Enllaç d'etiqueta (/tag/:slug/)
  if (segments[0] === 'tag' || segments[0] === 'etiqueta') {
    return `/mur?tag=${encodeURIComponent(lastSlug)}${hash}`;
  }

  // 3. Permalink amb data /AAAA/MM/DD/:slug/ o Blogger /AAAA/MM/:slug.html
  if (/^\d{4}$/.test(segments[0]) && lastSlug) {
    if (MAPA_ARTICLES_WP_425[lastSlug]) {
      return MAPA_ARTICLES_WP_425[lastSlug] + hash;
    }
    if (lastSlug === '2n-aplec-pel-territori' || lastSlug === 'aplec-2023') {
      return '/events/aplec-2023' + hash;
    }
    return `/mur/${lastSlug}${hash}`;
  }

  // 4. Comprovació directa contra el mapa de 425 articles, 18 pàgines o 114 categories
  if (MAPA_ARTICLES_WP_425[lastSlug]) return MAPA_ARTICLES_WP_425[lastSlug] + hash;
  if (MAPA_PAGINES_WP_18[lastSlug]) return MAPA_PAGINES_WP_18[lastSlug] + hash;
  if (MAPA_CATEGORIES_WP_114[lastSlug]) return MAPA_CATEGORIES_WP_114[lastSlug] + hash;

  // 5. Fallback per a pàgines d'un sol segment a socdepoble.net/:slug/
  if (segments.length === 1 && lastSlug) {
    return `/page/${lastSlug}${hash}`;
  }

  return null;
}

/**
 * Reescriu tots els atributs href="..." de socdepoble.net i antic Blogger dins
 * d'un fragment HTML cap a les rutes internes de Sóc de Poble, retornant
 * { html, totalReescrits, enllacosReescrits }.
 */
export function reescriuEnllacosHtmlSocDePobleNet(html) {
  if (typeof html !== 'string' || !html) {
    return { html: '', totalReescrits: 0, enllacosReescrits: [] };
  }
  const enllacosReescrits = [];
  const nextHtml = html.replace(
    /href=(["'])(https?:\/\/(?:www\.)?(?:socdepoble\.(?:net|org|cat)|[a-z0-9-]+\.blogspot\.com)\/[^"']*)\1/gi,
    (fullMatch, quote, rawUrl) => {
      const rutaInterna = resolRutaInternaSocDePobleNet(rawUrl);
      if (!rutaInterna) return fullMatch;
      enllacosReescrits.push({ original: rawUrl, desti: rutaInterna });
      return `href=${quote}${rutaInterna}${quote} data-sdp-rewritten-from=${quote}${rawUrl}${quote}`;
    }
  );
  return {
    html: nextHtml,
    totalReescrits: enllacosReescrits.length,
    enllacosReescrits,
  };
}

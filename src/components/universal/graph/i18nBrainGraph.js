export function codiLlenguaBrainGraph(language = 'ca') {
  const base = String(language || 'ca').toLowerCase().split('-')[0];
  return Object.hasOwn(DICCIONARI_BRAIN_GRAPH, base) ? base : 'ca';
}

export function textosBrainGraphA11y(language = 'ca') {
  return DICCIONARI_BRAIN_GRAPH[codiLlenguaBrainGraph(language)];
}

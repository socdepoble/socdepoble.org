/** El parell d'un text pel seu nom relatiu ('rebost.perComprar'); un de desconegut, la clau mateixa com a reserva. */
export const parellComu = (nom) => TEXTOS_COMU[nom] ?? Object.freeze([`section.comu.${nom}`, nom]);

/** El parell del text d'un error del nucli pel seu `codi` (un altre, «desconegut»). */
export const parellDError = (error) => TEXTOS_COMU[`error.${camelDe(error?.codi)}`] ?? TEXTOS_COMU['error.desconegut'];

export function textXatV1225(idioma, clau, variables = null) {
  const codi = normalitzaLlenguaXat(idioma);
  const taula = TEXTOS_XAT_V1225[codi] || TEXTOS_XAT_V1225.ca;
  let text = taula[clau] ?? TEXTOS_XAT_V1225.ca[clau] ?? clau;
  if (variables && typeof variables === 'object') {
    for (const [k, v] of Object.entries(variables)) {
      text = text.replaceAll(`{${k}}`, () => String(v ?? ''));
    }
  }
  return text;
}

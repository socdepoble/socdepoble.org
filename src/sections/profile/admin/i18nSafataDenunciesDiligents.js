export function textosSafataLssi(idioma) {
  const codi = String(idioma || 'ca').slice(0, 2).toLowerCase();
  return DICCIONARI_SAFATA_LSSI[codi] || DICCIONARI_SAFATA_LSSI.ca;
}

export function etiquetaEstatDenuncia(estat, tx) {
  if (estat === 'rebuda') return tx.estatRebuda;
  if (estat === 'en_revisio') return tx.estatEnRevisio;
  if (estat === 'ocultacio_cautelar') return tx.estatOcultacioCautelar;
  if (estat === 'resolta') return tx.estatResolta;
  return tx.estatArxivada;
}

export function etiquetaMotiuDenuncia(motiu, submotiuLssi, tx) {
  const base = motiu === 'ofensiu'
    ? tx.motiuOfensiu
    : motiu === 'spam_frau'
      ? tx.motiuSpamFrau
      : motiu === 'desinformacio'
        ? tx.motiuDesinformacio
        : tx.motiuAltre;
  return submotiuLssi ? `${base} (${submotiuLssi})` : base;
}

export function etiquetaAccioTransicio(estatDesti, tx) {
  if (estatDesti === 'en_revisio') return tx.accioPassaEnRevisio;
  if (estatDesti === 'ocultacio_cautelar') return tx.accioRetiradaCautelar;
  if (estatDesti === 'resolta') return tx.accioMarcaResolta;
  return tx.accioDesestimaArxiva;
}

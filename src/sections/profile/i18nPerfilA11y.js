export function codiLlenguaPerfil({ language = null, t = null } = {}) {
  if (typeof language === 'string' && language.trim()) {
    const base = language.trim().toLowerCase().split('-')[0];
    if (Object.hasOwn(DICCIONARI_PERFIL_A11Y, base)) return base;
  }
  if (typeof t === 'function') {
    const mostra = t('section.xat.ajustos.tancaSessio', 'Tanca la sessió');
    if (mostra === 'Cerrar sesión') return 'es';
    if (mostra === 'Log out') return 'en';
    if (mostra === 'Itxi saioa') return 'eu';
    if (mostra === 'Pechar sesión') return 'gl';
  }
  return 'ca';
}

export function textosPerfilA11y(opcions = {}) {
  return DICCIONARI_PERFIL_A11Y[codiLlenguaPerfil(opcions)];
}

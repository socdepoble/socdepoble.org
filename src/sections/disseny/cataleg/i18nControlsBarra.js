export function localitzaItemCataleg(item, llengua = 'ca') {
  if (!item || item.id !== 'fonaments-controls-barra') return item;
  const codi = normalitzaLlenguaDisseny(llengua);
  const meta = METADADES_CONTROLS_BARRA[codi];
  return {
    ...item,
    title: meta.title,
    subtitle: meta.subtitle,
    lead: meta.lead,
    tags: meta.tags,
    categoriaLabel: meta.categoria,
    contentLanguage: codi,
  };
}


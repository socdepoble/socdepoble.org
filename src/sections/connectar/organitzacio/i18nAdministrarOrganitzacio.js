export function normalitzaIdiomaAdministrarOrg(idioma) {
  const base = String(idioma || 'ca').trim().toLowerCase().split(/[-_]/)[0];
  return Object.hasOwn(TEXTOS, base) ? base : 'ca';
}

export function textosAdministrarOrg(idioma = 'ca') {
  return TEXTOS[normalitzaIdiomaAdministrarOrg(idioma)];
}

export function localeDataAdministrarOrg(idioma = 'ca') {
  return LOCALES_DATA[normalitzaIdiomaAdministrarOrg(idioma)];
}

export function etiquetaRolAdministrarOrg(rol, idioma = 'ca') {
  const tx = textosAdministrarOrg(idioma);
  switch (rol) {
    case 'owner': return tx.rolOwner;
    case 'admin': return tx.rolAdmin;
    case 'member': return tx.rolMember;
    default: return null;
  }
}

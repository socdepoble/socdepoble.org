export function resolTextosSalutDispositiu(idioma = 'ca') {
  const codi = String(idioma || 'ca').toLowerCase().split('-')[0];
  return TEXTOS_SALUT_DISPOSITIU[codi] || TEXTOS_SALUT_DISPOSITIU.ca;
}

export function interpolaSalut(plantilla, valors = {}) {
  return String(plantilla || '').replace(/\{([a-zA-Z0-9_]+)\}/g, (_, clau) => (
    Object.hasOwn(valors, clau) && valors[clau] !== null && valors[clau] !== undefined
      ? String(valors[clau])
      : ''
  ));
}

export function formataBytesHumans(bytes, idioma = 'ca') {
  if (typeof bytes !== 'number' || !Number.isFinite(bytes) || bytes < 0) return '0 B';
  if (bytes === 0) return '0 B';
  const unitats = ['B', 'KB', 'MB', 'GB', 'TB'];
  let valor = bytes;
  let index = 0;
  while (valor >= 1024 && index < unitats.length - 1) {
    valor /= 1024;
    index += 1;
  }
  const locale = { ca: 'ca-ES', es: 'es-ES', en: 'en-GB', eu: 'eu-ES', gl: 'gl-ES' }[
    String(idioma || 'ca').toLowerCase().split('-')[0]
  ] || 'ca-ES';
  const decimals = index === 0 ? 0 : valor >= 100 ? 0 : 1;
  const formatat = new Intl.NumberFormat(locale, {
    minimumFractionDigits: 0,
    maximumFractionDigits: decimals,
  }).format(valor);
  return `${formatat} ${unitats[index]}`;
}
